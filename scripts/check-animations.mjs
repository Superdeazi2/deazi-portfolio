import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {transformSync} from '../node_modules/esbuild/lib/main.js';
const source=fs.readFileSync('src/views/app.ts','utf8');
const part=source.slice(source.indexOf('function startFrameLoop('),source.indexOf('function initFoxLoader()'));
const queue=[];let time=0;let enabled=false;const events=new Map();const shown=[];
const window={matchMedia:()=>({matches:true}),requestAnimationFrame:fn=>(queue.push(fn),queue.length),cancelAnimationFrame:()=>{},addEventListener:(name,fn)=>events.set(name,fn)};
